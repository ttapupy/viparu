#!/usr/bin/env python3
"""Prepare standalone Shell SCSS; never modify the vendored Yaru/GNOME sources."""

import argparse
import re
from pathlib import Path

SHELL_DIR = Path(__file__).resolve().parent
UPSTREAM = SHELL_DIR / "upstream/theme/gnome-shell-sass"
YARU = SHELL_DIR / "src/gnome-shell-sass"
OUTPUT = SHELL_DIR / ".build/scss"

# Only CSS-loaded theme artwork is needed, not the whole icon resource bundle.
THEME_ASSETS = {
    "calendar-today.svg",
    "calendar-today-light.svg",
    "dash-placeholder.svg",
    "gnome-shell-start.svg",
    "workspace-placeholder.svg",
}
METRO_ASSETS = {
    "./media/highlight_stacked_bg.svg",
    "./media/highlight_stacked_bg_h.svg",
}
RESOURCE_PREFIX = "resource:///org/gnome/shell/theme/"

# Comments and strings are tokens too: never rewrite prose, selectors or URLs
# while replacing actual color values. The URL branch precedes quoted strings.
TOKENS = re.compile(
    r"(?P<comment>/\*.*?\*/|//[^\n]*)"
    r"|(?P<url>\burl\(\s*(?P<quote>['\"])(?P<url_value>[^'\"]+)(?P=quote)\s*\))"
    r"|(?P<string>\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*')"
    r"|(?P<rgba>\brgba\(\s*(?P<red>\d+)\s*,\s*(?P<green>\d+)\s*,\s*"
    r"(?P<blue>\d+)\s*,\s*(?P<alpha>\d*\.?\d+)\s*\))"
    r"|(?P<accent>(?<![\w-])-st-accent(?:-fg)?-color(?![\w-]))"
    r"|(?P<hex>\#(?:000000|ffffff|000|fff)(?![\w-]))"
    r"|(?P<neutral>(?<![\w$#.-])(?:black|white)(?![\w-]))",
    re.DOTALL | re.IGNORECASE,
)
RGB_ROLES = {
    (0, 0, 0): "$gp-shell-bg",
    (255, 255, 255): "$gp-shell-fg",
    (238, 238, 238): "$gp-shell-fg",
    (34, 34, 38): "$gp-shell-bg",  # Yaru Looking Glass's fixed dark gray
    (255, 0, 0): "$gp-error",  # dock's original notification badge
}


def local_url(value: str) -> str:
    if value in METRO_ASSETS:
        # _gp-tweaks.scss supplies a CSS-only Metro focus cue.
        return "none"
    if not value.startswith(RESOURCE_PREFIX):
        raise ValueError(f"Unmapped Shell asset URL: {value}")
    name = value[len(RESOURCE_PREFIX):]
    if name not in THEME_ASSETS or not (SHELL_DIR / "src" / name).is_file():
        raise ValueError(f"Missing or unexpected Shell theme asset: {value}")
    # Relative to gnome-shell.css, NOT to the generated SCSS file.
    return f'url("src/{name}")'


def transform(source: str) -> str:
    def replace(match: re.Match) -> str:
        if match.group("url"):
            return local_url(match.group("url_value"))
        if match.group("accent"):
            return "$gp-accent-fg" if "-fg-" in match.group() else "$gp-accent-bg"
        if match.group("rgba"):
            rgb = (int(match.group("red")), int(match.group("green")), int(match.group("blue")))
            alpha = match.group("alpha")
            if rgb == (3, 2, 1) and float(alpha) == 0:
                # GNOME uses this exact transparent chroma key for occlusion;
                # it is a rendering sentinel, not a visible palette color.
                return match.group()
            if rgb not in RGB_ROLES:
                raise ValueError(f"Unmapped literal color: {match.group()}")
            return f"rgba({RGB_ROLES[rgb]}, {alpha})"
        if match.group("hex"):
            return "$gp-shell-bg" if match.group().lower().startswith("#0") else "$gp-shell-fg"
        if match.group("neutral"):
            return "$gp-shell-bg" if match.group().lower() == "black" else "$gp-shell-fg"
        return match.group()

    return TOKENS.sub(replace, source)


def prepared_sources() -> dict[Path, str]:
    sources = {
        Path("upstream") / name: UPSTREAM / name
        for name in ("_drawing.scss", "_common.scss", "_widgets.scss")
    }
    sources.update({
        Path("upstream/widgets") / path.name: path
        for path in sorted((UPSTREAM / "widgets").glob("*.scss"))
    })
    sources.update({Path("yaru") / name: YARU / name for name in ("_dock.scss", "_tweaks.scss")})
    result = {}
    for relative, path in sources.items():
        source = path.read_text(encoding="utf-8")
        result[relative] = (
            f"// Generated by prepare_sources.py from {path.relative_to(SHELL_DIR)}.\n"
            + transform(source)
        )

    # Fail on incomplete source snapshots instead of accidentally using stale
    # generated partials or compiler include paths from a different Shell.
    for relative, source in result.items():
        uncommented = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.DOTALL)
        for imported in re.findall(r"@import\s+['\"]([^'\"]+)['\"]\s*;", uncommented):
            name = Path(imported)
            partial = relative.parent / name.parent / ("_" + name.stem.lstrip("_") + ".scss")
            if partial not in result:
                raise ValueError(f"Missing upstream import in {relative}: {imported}")
    return result


def prepare(*, check: bool = False) -> int:
    sources = prepared_sources()
    for relative, source in sources.items():
        destination = OUTPUT / relative
        if check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != source:
                raise ValueError(f"Generated source is missing or stale: {destination}")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(source, encoding="utf-8")
    return len(sources)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check prepared sources without writing")
    args = parser.parse_args()
    try:
        count = prepare(check=args.check)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Shell source preparation failed: {error}\n")
    print(f"{'Checked' if args.check else 'Prepared'} {count} Shell SCSS files in {OUTPUT}")


if __name__ == "__main__":
    main()
